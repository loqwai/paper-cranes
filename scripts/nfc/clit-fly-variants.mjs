// Generate the clit-set NFC variants as clit-set/2 FLIGHTS: 200 tags, clit-new/2 .. clit-new/201.
//
//   node scripts/nfc/clit-fly-variants.mjs
//
// Writes shaders/clit-set/nfc-variants.json ([{n,name,title,shader,mood,knobs,voyage0,short,full}], the shape
// scripts/nfc/render-gate.mjs and scripts/nfc/short-links.mjs read) and shaders/clit-set/nfc-variants.md.
// Deterministic: same inputs, same URLs.
//
// Recipe (Aaron 2026-11-27: "they should be variants of clit-set/2"):
//   - clit-set/2 with controller=clit-pilot then clit-set, fly=1: the phone flies forward through the fractal
//     on its own (controllers/clit-set.js FLIGHT), the pilot plays the light knobs from the music.
//   - voyage0 = frac(n * 0.618) * 6: each tag opens on its own landmark of the voyage.
//   - knob_9 HUE stepped over its full range by the golden ratio: each tag its own palette phase.
//   - a named light mood per tag plus golden-ratio jitter, inside the bands the pilot itself uses.
//   - No seeds in the URL: per-phone seeds vary the lace and palette, so one tag differs on two phones.
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '../..')
const ORIGIN = 'https://visuals.beadfamous.com/'
const FIRST = 2, COUNT = 200
const PHI = 0.6180339887
const WAYPOINTS = ['home', 'ribbon cathedral', 'vortex eye', 'jellyfish tendrils', 'fern galaxy', 'rose carpet']

// Light moods (k10 NEBULA, k11 TRAILS, k12 REACT, k14 EMBER, k16 LACE), inside pilot-brain's light bands
const MOODS = [
  { name: 'Ember Drift', knobs: { 10: 0.35, 11: 0.2, 12: 0.45, 14: 0.45, 16: 0.4 } },
  { name: 'Deep Space', knobs: { 10: 0.6, 11: 0.15, 12: 0.35, 14: 0.25, 16: 0.3 } },
  { name: 'Filigree Rush', knobs: { 10: 0.25, 11: 0.3, 12: 0.55, 14: 0.35, 16: 0.6 } },
  { name: 'Comet Trails', knobs: { 10: 0.45, 11: 0.4, 12: 0.4, 14: 0.4, 16: 0.45 } },
]
const JITTER = 0.08
const frac = x => x - Math.floor(x)
const r3 = x => Math.round(x * 1000) / 1000
const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x))

const variants = []
for (let i = 0; i < COUNT; i++) {
  const n = FIRST + i
  const mood = MOODS[i % MOODS.length]
  const knobs = { 9: r3(0.03 + 0.94 * frac(n * PHI * 7)) }
  for (const [k, base] of Object.entries(mood.knobs)) knobs[k] = r3(clamp(base + (frac(n * PHI * (Number(k) + 3)) * 2 - 1) * JITTER, 0, 0.9))
  const voyage0 = r3(frac(n * PHI) * 6)
  const wp = WAYPOINTS[Math.floor(voyage0 % 6)]
  const q = ['shader=clit-set/2', 'controller=clit-pilot', 'controller=clit-set', 'fly=1', 'wavelet=true', 'fft_size=2048', 'smoothing=0.3', `voyage0=${voyage0}`,
    ...Object.entries(knobs).map(([k, v]) => `knob_${k}=${v}`)].join('&')
  variants.push({
    n, name: `clit-new-${n}`, title: `Flight · ${mood.name} · ${wp}`, shader: 'clit-set/2', color: 'clit-set', mood: mood.name,
    knobs, voyage0, short: `https://2cb.pw/clit-new/${n}`, full: `${ORIGIN}?${q}`,
  })
}

writeFileSync(`${ROOT}/shaders/clit-set/nfc-variants.json`, JSON.stringify(variants, null, 1) + '\n')
writeFileSync(`${ROOT}/shaders/clit-set/nfc-variants.md`, [
  '# clit-set NFC variants: clit-set/2 flights',
  '',
  'Generated by `node scripts/nfc/clit-fly-variants.mjs`. Each tag opens clit-set/2 in fly mode (forward-only flight,',
  'the in-page pilot playing the light knobs) on its own landmark and palette. Per-phone seeds vary it further.',
  '',
  '| n | short | title | voyage0 | open |',
  '|---|---|---|---|---|',
  ...variants.map(v => `| ${v.n} | [clit-new/${v.n}](${v.short}) | ${v.title} | ${v.voyage0} | [full](${v.full}) |`),
  '',
].join('\n'))
console.log(JSON.stringify({ count: variants.length, longest: Math.max(...variants.map(v => v.full.length)), sample: variants[0].full }))
